export function t(lang: Language, key: string, params?: Record<string, string | number>): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.vi;
  let text = dict[key] ?? TRANSLATIONS.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}

export function resourceLabel(lang: Language, res: ResourceType): string {
  return t(lang, res);
}

export function terrainLabel(lang: Language, terrain: TerrainType): string {
  return t(lang, terrain);
}

export function devCardLabel(lang: Language, card: DevCardType): string {
  return t(lang, card);
}

export function harborLabel(lang: Language, harbor: HarborType): string {
  if (harbor === 'generic') return t(lang, 'genericHarbor');
  return `${t(lang, 'resourceHarbor')} (${resourceLabel(lang, harbor)})`;
}

